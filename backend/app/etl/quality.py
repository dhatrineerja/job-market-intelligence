"""Write docs/data_quality.md from the current database contents."""

from collections import Counter
from collections.abc import Sequence
from pathlib import Path

from sqlalchemy import Connection, text

REPORT_PATH = Path(__file__).resolve().parents[3] / "docs" / "data_quality.md"

SECTIONS: list[tuple[str, str]] = [
    (
        "Rows and salary coverage by source",
        """
        SELECT source, country, count(*) AS jobs, count(salary_mid) AS with_salary,
               round(100.0 * count(salary_mid) / count(*), 1) AS salary_pct,
               round(100.0 * count(description) / count(*), 1) AS description_pct,
               round(avg(length(description)))::int AS avg_description_chars
        FROM jobs GROUP BY source, country ORDER BY jobs DESC
        """,
    ),
    (
        "Median annual salary by role family and currency (roles with 30+ salaries)",
        """
        SELECT salary_currency AS currency, role_family, count(*) AS with_salary,
               round(percentile_cont(0.5) WITHIN GROUP (ORDER BY salary_mid))::bigint AS median
        FROM jobs WHERE salary_mid IS NOT NULL
        GROUP BY salary_currency, role_family HAVING count(*) >= 30
        ORDER BY currency, with_salary DESC
        """,
    ),
    (
        "Top Indian cities (a multi-city job counts once per city)",
        """
        SELECT l.city, count(*) AS jobs, count(j.salary_mid) AS with_salary
        FROM jobs j
        JOIN job_locations jl ON jl.job_id = j.id
        JOIN locations l ON l.id = jl.location_id
        WHERE l.country = 'IN' AND l.city IS NOT NULL
        GROUP BY l.city ORDER BY jobs DESC LIMIT 12
        """,
    ),
    (
        "India salary rows by city and role (data roles, 5+ salaries)",
        """
        SELECT l.city, j.role_family, count(*) AS with_salary
        FROM jobs j
        JOIN job_locations jl ON jl.job_id = j.id
        JOIN locations l ON l.id = jl.location_id
        WHERE j.salary_currency = 'INR' AND l.city IS NOT NULL
          AND j.role_family IN ('ml_engineer', 'data_scientist', 'data_analyst', 'data_engineer')
        GROUP BY l.city, j.role_family HAVING count(*) >= 5
        ORDER BY with_salary DESC LIMIT 20
        """,
    ),
    (
        "India jobs and salaries by listing year",
        """
        SELECT extract(year FROM listed_at)::int AS year, count(*) AS jobs,
               count(salary_mid) AS with_salary,
               count(*) FILTER (WHERE role_family IN
                   ('ml_engineer', 'data_scientist', 'data_analyst', 'data_engineer')
                   AND salary_mid IS NOT NULL) AS data_role_salaries
        FROM jobs WHERE country = 'IN' GROUP BY 1 ORDER BY 1
        """,
    ),
    (
        "Listing dates by source",
        """
        SELECT source, min(listed_at)::date AS earliest, max(listed_at)::date AS latest,
               count(*) FILTER (WHERE listed_at IS NULL) AS missing
        FROM jobs GROUP BY source ORDER BY source
        """,
    ),
    (
        "Null rates",
        """
        SELECT source,
               round(100.0 * count(*) FILTER (WHERE company_id IS NULL) / count(*), 1)
                   AS no_company_pct,
               round(100.0 * count(*) FILTER (WHERE experience_level IS NULL) / count(*), 1)
                   AS no_experience_pct,
               round(100.0 * count(*) FILTER (WHERE skills_raw IS NULL) / count(*), 1)
                   AS no_skill_tags_pct
        FROM jobs GROUP BY source ORDER BY source
        """,
    ),
]


def _table(columns: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(str(value) for value in row) + " |" for row in rows]
    return "\n".join(lines)


def write_report(conn: Connection, stats: dict[str, Counter]) -> Path:
    keys = [
        "rows_read",
        "rows_dropped",
        "rows_repaired",
        "duplicates_merged",
        "files_skipped",
        "salaries_rejected",
    ]
    ingest_rows = [[source, *(counter[key] for key in keys)] for source, counter in stats.items()]
    parts = [
        "# Data quality report",
        "Generated by `python -m app.etl.run`. Do not edit by hand.",
        "## Ingestion",
        "`rows_dropped` counts duplicates, untitled rows and unreadable rows. "
        "`rows_repaired` counts malformed rows that were fixed. "
        "`duplicates_merged` counts repeat sightings of one job. "
        "`files_skipped` counts files in a different layout. `salaries_rejected` counts "
        "salaries outside the plausible range.",
        _table(["source", *keys], ingest_rows),
    ]
    for title, query in SECTIONS:
        result = conn.execute(text(query))
        parts += [f"## {title}", _table(list(result.keys()), result.fetchall())]

    REPORT_PATH.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    return REPORT_PATH
